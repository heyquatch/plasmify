"""Splash screen (shown while Plasma starts).

Plasmify writes a tiny splash package: one QML file plus up to two images,
coloured from the palette. Every value goes into the QML through ``json.dumps``,
so nothing from a preset can break out of a string.
"""

from __future__ import annotations

import json
import shutil
from collections.abc import Callable
from pathlib import Path

from plasmify import backup, downloads, glass
from plasmify.distro import parse_os_release
from plasmify.presets import Preset
from plasmify.steps.base import Context, Step
from plasmify.steps.wallpaper import cached_file, image_name, wallpaper_dir
from plasmify.system import CONFIG_HOME, DATA_HOME, PLASMIFY_DATA, safe_child

PACKAGE_ROOT = DATA_HOME / "plasma" / "look-and-feel"
BREEZE_SPLASH = "org.kde.breeze.desktop"
PLASMA_LOGO = "/usr/share/plasma/look-and-feel/org.kde.breeze.desktop/contents/splash/images/plasma.svgz"

SPLASH_QML = """import QtQuick
import org.kde.kirigami as Kirigami

// Generated by Plasmify. Plasma sets "stage" from 1 to 6 while it starts.
Rectangle {
    id: root
    color: %(background)s
    property int stage

    Image {
        anchors.fill: parent
        visible: %(has_image)s
        source: %(image)s
        fillMode: Image.PreserveAspectCrop
        asynchronous: true
    }
    Rectangle {
        anchors.fill: parent
        visible: %(has_image)s
        color: %(background)s
        opacity: 0.45
    }
    Rectangle {
        // A soft card keeps the logo and text readable on busy images.
        anchors.centerIn: content
        visible: %(has_image)s
        width: content.width + Kirigami.Units.gridUnit * 4
        height: content.height + Kirigami.Units.gridUnit * 3
        radius: Kirigami.Units.gridUnit * 1.5
        color: %(background)s
        opacity: content.opacity * 0.75
    }

    Column {
        id: content
        anchors.centerIn: parent
        spacing: Kirigami.Units.gridUnit
        opacity: root.stage >= 1 ? 1 : 0
        Behavior on opacity { NumberAnimation { duration: 600; easing.type: Easing.InOutQuad } }

        Kirigami.Icon {
            anchors.horizontalCenter: parent.horizontalCenter
            visible: %(has_logo)s
            source: %(logo)s
            width: Kirigami.Units.gridUnit * 7
            height: width
        }
        Text {
            anchors.horizontalCenter: parent.horizontalCenter
            visible: text.length > 0
            text: %(text)s
            textFormat: Text.PlainText  // styled text would load <img> tags from any host
            color: %(foreground)s
            font.pointSize: 20
            font.weight: Font.DemiBold
        }
        Rectangle {
            anchors.horizontalCenter: parent.horizontalCenter
            visible: %(progress)s
            width: Kirigami.Units.gridUnit * 14
            height: 6
            radius: 3
            color: %(track)s
            Rectangle {
                width: parent.width * Math.min(root.stage, 6) / 6
                height: parent.height
                radius: 3
                color: %(accent)s
                Behavior on width { NumberAnimation { duration: 400; easing.type: Easing.OutCubic } }
            }
        }
    }
}
"""


GENERATED_PREFIX = "plasmify-splash-"


def package_id(preset: Preset) -> str:
    return f"{GENERATED_PREFIX}{preset.id}"


def generated(theme: str | None) -> bool:
    """Whether ``theme`` is a splash Plasmify generated (see package_id)."""
    return bool(theme) and theme.startswith(GENERATED_PREFIX)


# A preset without [splash] leaves the splash screen to the user, as the preset reference promises
# for every section left out, the way panelstyle.keep_own_style does for the Plasma style. A splash
# Plasmify generated is the last preset's leftover, not the user's choice (Crimson Moon's stayed on
# every preset applied after it), so the one from the pinned "Your setup before Plasmify" backup
# comes back, or the distribution's default when that backup has none. The colour step runs this, as it runs
# for every preset.
def own_splash() -> tuple[str | None, str | None]:
    """The (Engine, Theme) of the splash screen the user had before Plasmify, from the pinned
    backup. A key it leaves out is None (the default); (None, None) also when the backup does not
    hold ksplashrc, cannot be read, or names a splash Plasmify generated as well."""
    try:
        pinned = next((b for b in backup.list_backups(backup.BACKUP_ROOT) if b.pinned), None)
        text = backup.stored_text(pinned, CONFIG_HOME / "ksplashrc") if pinned else None
    except (OSError, KeyError, TypeError, ValueError):  # a damaged manifest never stops the apply
        return None, None
    if not text:
        return None, None
    theme = glass.get_key(text, "KSplash", "Theme")
    if generated(theme):
        return None, None
    return glass.get_key(text, "KSplash", "Engine"), theme


def keep_own_splash(ctx: Context) -> None:
    """The splash screen for a preset without one: the user's own (see above)."""
    if not generated(ctx.runner.kread("ksplashrc", "KSplash", "Theme")):
        return  # the user's own splash, or KDE's default: left as it is
    engine, theme = own_splash()
    if engine is None and theme is None:
        ctx.log("Putting the default splash screen back")
    else:
        ctx.log(f"Putting your own splash screen back ({theme or engine})")
    for key, value in (("Engine", engine), ("Theme", theme)):
        if value:
            ctx.runner.kwrite("ksplashrc", "KSplash", key, value)
        else:
            ctx.runner.krevert(CONFIG_HOME / "ksplashrc", "KSplash", key)  # the distribution's splash


def distro_logo() -> str:
    try:
        info = parse_os_release(Path("/etc/os-release").read_text(errors="replace"))
    except OSError:
        return "distributor-logo"
    return info.get("LOGO") or "distributor-logo"


def splash_qml(preset: Preset, image: str | None, logo: str | None, text: str, progress: bool) -> str:
    p = preset.palette
    return SPLASH_QML % {
        "background": json.dumps(p.crust),
        "foreground": json.dumps(p.text),
        "accent": json.dumps(p.accent),
        "track": json.dumps(p.surface),
        "has_image": json.dumps(image is not None),
        "image": json.dumps(image or ""),
        "has_logo": json.dumps(logo is not None),
        "logo": json.dumps(logo or ""),
        "text": json.dumps(text),
        "progress": json.dumps(bool(progress)),
    }


def metadata(preset: Preset) -> str:
    return json.dumps(
        {
            "KPackageStructure": "Plasma/LookAndFeel",
            "KPlugin": {
                "Id": package_id(preset),
                "Name": f"Plasmify {preset.name} splash",
                "Description": "Splash screen generated by Plasmify.",
                "License": "MIT",
                "Version": "1",
            },
            "X-Plasma-APIVersion": "2",
        },
        indent=2,
    )


def _own_file(preset: Preset, name: str, warn: Callable[[str], None]) -> Path | None:
    if preset.asset_dir is None:
        warn(f"{name} needs a saved or imported preset")
        return None
    path = safe_child(preset.asset_dir, name)
    if not path.is_file() or not downloads.is_image(path):
        warn(f"{name} is missing or not an image")
        return None
    return path


def _background(preset: Preset, splash: dict, warn: Callable[[str], None]) -> Path | None:
    choice = splash.get("background", "palette")
    if choice == "image" and "background_file" in splash:
        return _own_file(preset, splash["background_file"], warn)
    if choice == "wallpaper":
        images = preset.section("wallpaper").get("images", [])
        if images:
            local = (
                safe_child(preset.asset_dir, images[0]["file"]) if preset.asset_dir and "file" in images[0] else None
            )
            candidate = local if local and local.is_file() else wallpaper_dir(preset) / image_name(1, images[0])
            if not candidate.is_file():
                candidate = cached_file(preset, images[0])  # e.g. downloaded under an older name
            if candidate is not None and candidate.is_file():
                return candidate
            warn("The wallpaper is not downloaded yet; apply the Wallpapers step too")
    return None


def _logo(preset: Preset, splash: dict, warn: Callable[[str], None]) -> tuple[str | None, Path | None]:
    """(QML source, file to copy into the package)."""
    choice = splash.get("logo", "distro")
    if choice == "none":
        return None, None
    if choice == "plasma":
        return PLASMA_LOGO, None
    if choice == "image" and "logo_file" in splash:
        path = _own_file(preset, splash["logo_file"], warn)
        return (None, None) if path is None else ("images/logo" + path.suffix.lower(), path)
    if choice == "preset":
        icon = next(iter(sorted((PLASMIFY_DATA / "icons").glob(f"{preset.id}.*"))), None)
        if icon is not None:
            return "images/logo" + icon.suffix.lower(), icon
    return distro_logo(), None


def write_package(root: Path, preset: Preset, warn: Callable[[str], None]) -> None:
    """Write the splash package for ``preset`` into ``root`` (replacing what is there)."""
    splash = preset.section("splash")
    if root.exists():
        shutil.rmtree(root)
    images = root / "contents" / "splash" / "images"
    images.mkdir(parents=True)
    background = _background(preset, splash, warn)
    image_source = None
    if background is not None:
        target = images / ("background" + background.suffix.lower())
        with background.open("rb") as handle:
            animated = downloads.is_animated(handle.read(64))
        if animated:
            # The splash shows one still picture: the first frame, never a whole animation.
            try:
                target = images / "background.png"
                target.write_bytes(downloads.still_png(background.read_bytes()))
            except (ValueError, OSError) as exc:
                warn(f"The splash background could not be used: {exc}")
                target = None
        else:
            shutil.copyfile(background, target)
        image_source = "images/" + target.name if target is not None else None
    logo_source, logo_file = _logo(preset, splash, warn)
    if logo_file is not None and logo_source:
        shutil.copyfile(logo_file, root / "contents" / "splash" / logo_source)
    qml = splash_qml(preset, image_source, logo_source, splash.get("text", ""), splash.get("progress", True))
    (root / "contents" / "splash" / "Splash.qml").write_text(qml)
    (root / "metadata.json").write_text(metadata(preset))


class SplashStep(Step):
    id = "splash"
    title = "Splash screen"
    description = "The screen shown while Plasma starts: colours, background, logo and text."

    def applies_to(self, preset: Preset) -> bool:
        return bool(preset.section("splash"))

    def touched_paths(self, preset: Preset) -> list[Path]:
        return [CONFIG_HOME / "ksplashrc", safe_child(PACKAGE_ROOT, package_id(preset))]

    def apply(self, ctx: Context) -> None:
        splash = ctx.preset.section("splash")
        style = splash.get("style", "plasmify")
        run = ctx.runner
        if style == "none":
            ctx.log("Turning the splash screen off")
            run.kwrite("ksplashrc", "KSplash", "Engine", "none")
            run.kwrite("ksplashrc", "KSplash", "Theme", "None")
            return
        if style == "breeze":
            ctx.log("Using the Breeze splash screen")
            run.kwrite("ksplashrc", "KSplash", "Engine", "KSplashQML")
            run.kwrite("ksplashrc", "KSplash", "Theme", BREEZE_SPLASH)
            return

        name = package_id(ctx.preset)
        ctx.log("Writing the splash screen")
        if not ctx.dry_run:
            root = safe_child(PACKAGE_ROOT, name)
            write_package(root, ctx.preset, ctx.warn)
            ctx.record(root)
        run.kwrite("ksplashrc", "KSplash", "Engine", "KSplashQML")
        run.kwrite("ksplashrc", "KSplash", "Theme", name)


def package_path(preset: Preset) -> Path:
    return PACKAGE_ROOT / package_id(preset)
