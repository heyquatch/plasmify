# Letters outside the font are shown as their base letter (common accents, dotted and dotless i).
FOLD = str.maketrans("ÇĞİIÖŞÜçğıiöşüÄÅÉÈÊËÑáàâäåéèêëíìîïñóòôúùûý", "CGIIOSUCGIIOSUAAEEEENAAAAAEEEEIIIINOOOUUUY")

ROWS = 5
MAX_LENGTH = 12


def normalise(text: str) -> str:
    return text.translate(FOLD).upper()


def supported(text: str) -> bool:
    """Whether ``text`` can be drawn (after folding accents) and is a sensible length."""
    folded = normalise(text)
    return 0 < len(text.strip()) <= MAX_LENGTH and all(c in GLYPHS for c in folded)


def render(text: str, scale: int = 1) -> list[str]:
    """``text`` as rows of block characters. ``scale`` 2 doubles width and height."""
    rows = [""] * ROWS
    for index, char in enumerate(normalise(text)):
        glyph = GLYPHS[char]
        for row in range(ROWS):
            rows[row] += ("" if index == 0 else " ") + glyph[row]
    drawn = [row.replace("#", "█").replace(".", " ").rstrip() for row in rows]
    if scale > 1:
        drawn = [line for row in drawn for line in [row.replace("█", "█" * scale).replace(" ", " " * scale)] * scale]
    return drawn
